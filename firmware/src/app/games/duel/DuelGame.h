/**
 * AI DUEL — じゃんけん 10 回勝負。相手（AI）は「あなたの次の手」を先に予測し、
 * 自分の手を**先に決めてから**勝負する。
 *
 * 入口 → 8 つのアイコンから自分を選ぶ（＋ゲスト）→ その人の記録 → 10 回勝負
 * → 10 回の結果 → 癖を見る、までを LVGL の画面 1 枚の中身を作り替えて進める
 * （人狼・探偵・エスパーと同じ作り）。
 *
 * 予測は Wi-Fi があれば Jev（GAS 経由）、無ければ端末内の統計 AI。
 * **端末内の統計 AI は必ず先に計算する**ので、通信が無くても・遅れても遊べる。
 * Jev の返事は「依頼から 9 秒以内 かつ 依頼番号が一致」したときだけ採用し、
 * いちど決めた AI の手は二度と選び直さない（設計書 1.2 / 5.4）。
 *
 * 記録は人（アイコン）ごとに NVS `ct_duel` へ 1 ラウンド確定ごとに保存する
 * （DuelStore.h）。ゲストは RAM だけで、次回には引き継がない。
 * 名前も PIN も持たないので、端末にもサーバーにも個人情報は出ない。
 *
 * シート（GAS）へ送る記録は**1 ラウンドごとには送らない**。GAS は Jev の呼び出しと
 * シートへの書き込みを終えてから答えるので、記録を予測の往復に相乗りさせると
 * 1 往復が 5 秒級になり、予測が毎回間に合わなかった（2026-09-22 の実機試験）。
 * 10 回ぶんを RAM にためて、けっか画面へ進んだとき（と、1 回以上確定した対戦を
 * 途中でやめたとき）に 1 往復だけで送る。送れなければ黙って捨てる。
 *
 * 詳しい取り決めは docs/AI_DUEL_PLAN.md（この実装の正）と
 * 参考データ/ゲーム4部作/COFFEE_TIME_AI_DUEL_Design_v1.0.md を参照。
 */
